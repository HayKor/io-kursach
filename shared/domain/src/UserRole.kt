package ru.haykor.sudv

/** Роль пользователя системы. */
enum class UserRole {
    /** Администратор: ведёт учётные записи. */
    ADMIN,

    /** Кадровик: ведёт сотрудников и взыскания, формирует отчёты. */
    HR,

    /** Руководитель: просматривает взыскания своего подразделения. */
    MANAGER,
}
